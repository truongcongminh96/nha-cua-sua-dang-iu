const storageKey = 'sua-bea.locale.v1';
function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === 'vi' || saved === 'zh') return saved;
  } catch {
    /* Storage disabled or restricted */
  }
  try {
    if (typeof navigator !== 'undefined' && navigator.language) {
      const navLang = navigator.language.toLowerCase();
      if (navLang.startsWith('zh')) return 'zh';
      return 'vi';
    }
  } catch {
    /* Ignore */
  }
  return 'vi';
}
let locale: Locale = readLocale();
const listeners = new Set<() => void>();
export function getLocale() { return locale; }
export function t(source: string) { return locale === 'vi' ? vietnamese[source] ?? source : source; }
export function setLocale(next: Locale) {
  if (next !== 'zh' && next !== 'vi') return;
  if (next === locale) return;
  locale = next;
  try { localStorage.setItem(storageKey, next); } catch { /* Changing language also works without storage. */ }
  listeners.forEach(listener => listener());
}
export function onLocaleChange(listener: () => void) { listeners.add(listener); return () => listeners.delete(listener); }
